const CODES = Object.keys(T).concat(Object.keys(ALIASES));

mkdirSync(outDir, { recursive: true });
for (const code of CODES) {
  const dict = ALIASES[code] ? T[ALIASES[code]] : T[code];
  const missing = KEYS.filter((k) => !(k in dict));
  const extra = Object.keys(dict).filter((k) => !KEYS.includes(k));
  if (missing.length || extra.length) {
    console.error(`${code}: missing=${missing} extra=${extra}`);
    process.exit(1);
  }
  // deterministic key order = KEYS order
  const ordered = Object.fromEntries(KEYS.map((k) => [k, dict[k]]));
  const file = join(outDir, `${code}.json`);
  writeFileSync(file, JSON.stringify(ordered, null, 2) + "\n", "utf8");
}
